import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {pgcrypto} from '@electric-sql/pglite/contrib/pgcrypto';

test('branch passwords protect operational records, writes, and searches without changing admin credentials',async()=>{
 const pg=new PGlite({extensions:{pgcrypto}});
 const user='00000000-0000-0000-0000-000000000001',sid='00000000-0000-0000-0000-000000000011',otherSid='00000000-0000-0000-0000-000000000012';
 try{
  await pg.exec(`create role authenticated;create role anon;create schema auth;
   create table auth.users(id uuid primary key,encrypted_password text);
   create table auth.sessions(id uuid primary key,user_id uuid references auth.users(id));
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create function auth.jwt() returns jsonb language sql stable as $$select jsonb_build_object('session_id',nullif(current_setting('request.jwt.claim.session_id',true),''))$$;
   grant usage on schema auth to authenticated;`);
  for(const file of ['schema.sql','002_academy_pricing.sql','003_qr_registration.sql','004_personal_details_registration.sql','005_multiple_membership_registration.sql','006_payment_security.sql'])await pg.exec(await readFile(`supabase/${file}`,'utf8'));
  await pg.exec(`alter table public.members add column "membershipNumber" integer;
   insert into auth.users values('${user}','unchanged-admin-hash');
   insert into auth.sessions values('${sid}','${user}'),('${otherSid}','${user}');
   insert into public.staff(id,name,email,role,"branchId") values('${user}','Admin','admin@example.test','SUPER ADMIN','dd');
   insert into public.branches(id,name,code) values('bd','Hybrid BD','BD');
   set request.jwt.claim.sub='${user}';set request.jwt.claim.session_id='${sid}';
   insert into public.members(id,name,"branchId") values('dd-member','DD member','dd'),('bd-member','BD member','bd');
   insert into public.memberships(id,"memberId","planId",start,expiry) values('dd-membership','dd-member','hybrid-boxing','2026-01-01','2026-02-01');`);
  await pg.exec(await readFile('supabase/migrations/20261118090000_workspace_queries_and_conflicts.sql','utf8'));
  await pg.exec(await readFile('supabase/migrations/20261122021643_branch_password_access.sql','utf8'));
  await pg.exec(`insert into private.branch_credentials select id,extensions.crypt('branch-test-password',extensions.gen_salt('bf',4)) from public.branches;
   set role authenticated;`);
  const current=async()=>(await pg.query<{branch:string|null}>('select public.current_branch() as branch')).rows[0].branch;
  const unlock=async(branch='bd',password='branch-test-password')=>(await pg.query<{ok:boolean}>('select public.unlock_branch($1,$2) as ok',[branch,password])).rows[0].ok;
  const ids=async(table='members')=>(await pg.query<{id:string}>(`select id from public.${table} order by id`)).rows.map(item=>item.id);
  assert.equal(await current(),null);
  assert.equal((await ids('branches')).length,2,'branch picker remains available');
  for(const table of ['members','memberships','membership_plans','classes','registration_requests'])assert.deepEqual(await ids(table),[]);
  assert.equal(await unlock('bd','wrong'),false);
  assert.equal(await unlock('missing'),false);
  assert.equal(await unlock('bd','x'.repeat(73)),false);
  assert.equal(await unlock(),true);
  assert.equal(await current(),'bd');
  assert.deepEqual(await ids(),['bd-member']);
  assert.deepEqual((await pg.query('select id from public.search_members($1,null)',['member'])).rows,[{id:'bd-member'}]);
  await assert.rejects(pg.query(`insert into public.members(id,name,"branchId") values('forged','Forged','dd')`),/row-level security/);
  await assert.rejects(pg.query(`update public.members set "branchId"='dd' where id='bd-member'`),/row-level security/);
  await pg.query(`update public.members set phone='123' where id='bd-member'`);
  await pg.exec(`set request.jwt.claim.session_id='${otherSid}'`);
  assert.equal(await current(),null,'another Auth session stays locked');
  assert.deepEqual(await ids(),[]);
  await pg.exec(`set request.jwt.claim.session_id='${sid}'`);
  assert.equal(await unlock('dd'),true);
  assert.deepEqual(await ids(),['dd-member']);
  assert.deepEqual(await ids('memberships'),['dd-membership']);
  await pg.exec('select public.lock_branch()');
  assert.deepEqual(await ids(),[]);
  for(let i=0;i<5;i++)assert.equal(await unlock('bd','wrong'),false);
  assert.equal(await unlock(),false,'five failed passwords lock further attempts');
  await pg.exec(`reset role;update private.branch_attempts set locked_until=now()-interval '1 second';set role authenticated;`);
  assert.equal(await unlock(),true);
  await pg.exec(`reset role;update private.branch_sessions set expires_at=now()-interval '1 second';set role authenticated;`);
  assert.equal(await current(),null,'branch access expires');
  assert.equal(await unlock(),true);
  await pg.exec(`reset role;update private.branch_credentials set password_hash=extensions.crypt('replacement-password',extensions.gen_salt('bf',4)) where branch_id='bd';set role authenticated;`);
  assert.equal(await current(),null,'password changes revoke prior unlocks');
  assert.equal(await unlock('bd','replacement-password'),true);
  await pg.exec(`reset role;delete from auth.sessions where id='${sid}';set role authenticated;`);
  assert.equal(await current(),null,'revoked Auth sessions cannot access branches');
  assert.equal(await unlock('dd'),false);
  await pg.exec('reset role');
  assert.deepEqual((await pg.query('select encrypted_password from auth.users')).rows,[{encrypted_password:'unchanged-admin-hash'}]);
  await pg.exec('set role anon');
  await assert.rejects(pg.query('select public.unlock_branch($1,$2)',['bd','replacement-password']),/permission denied/);
 }finally{await pg.close();}
});
