import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';

test('payment RLS requires an approved password and a live, unexpired Auth session', async () => {
 const pg=new PGlite({extensions:{pgcrypto}});
 const admin='00000000-0000-0000-0000-000000000001';
 const staff='00000000-0000-0000-0000-000000000002';
 const sid='00000000-0000-0000-0000-000000000011';
 const otherSid='00000000-0000-0000-0000-000000000012';
 const password='test777';
 const adminSid='00000000-0000-0000-0000-000000000013';
 const accountPassword='account-password777';
 const staffPassword='staff-secret777';
 try {
  await pg.exec(`create role authenticated;create role anon;create schema auth;
   create table auth.users(id uuid primary key,encrypted_password text);
   create table auth.sessions(id uuid primary key,user_id uuid references auth.users(id));
   create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
   create function auth.jwt() returns jsonb language sql stable as $$ select jsonb_build_object('session_id',nullif(current_setting('request.jwt.claim.session_id',true),'')) $$;`);
  for(const file of ['schema.sql','002_academy_pricing.sql','003_qr_registration.sql','004_personal_details_registration.sql','005_multiple_membership_registration.sql','006_payment_security.sql'])await pg.exec(await readFile(`supabase/${file}`,'utf8'));
  await pg.exec(await readFile('supabase/migrations/20261024091149_payment_section_scope.sql','utf8'));
  await pg.exec(await readFile('supabase/migrations/20261024091835_payment_import.sql','utf8'));
  await pg.exec(await readFile('supabase/migrations/20261024094934_staff_security.sql','utf8'));
  await pg.exec(await readFile('supabase/migrations/20261024103544_separate_staff_password.sql','utf8'));
  await pg.exec(`insert into auth.users(id,encrypted_password) values('${admin}',extensions.crypt('${accountPassword}',extensions.gen_salt('bf',4))),('${staff}',extensions.crypt('${accountPassword}',extensions.gen_salt('bf',4)));
   insert into private.staff_credentials(user_id,password_hash) select id,extensions.crypt('${staffPassword}',extensions.gen_salt('bf',4)) from auth.users;
   insert into auth.sessions values('${sid}','${staff}'),('${otherSid}','${staff}'),('${adminSid}','${admin}');
   insert into staff(id,name,email,role,"branchId") values('${admin}','Admin','admin@example.com','SUPER ADMIN','dd'),('${staff}','Staff','staff@example.com','STAFF','dd');
   set request.jwt.claim.sub='${admin}';
   insert into members(id,name,"branchId") values('member','Member','dd');
   insert into memberships(id,"memberId","planId",start,expiry) values('membership','member','hybrid-boxing','2026-01-01','2026-02-01');
   insert into payments(id,"memberId","membershipId",amount,date,method,status) values('payment','member','membership',170,'2026-01-01','Cash','Pending');
   grant usage on schema auth to authenticated;grant execute on all functions in schema auth to authenticated;
   set role authenticated;`);
  const login=async(user=staff,session=user===admin?adminSid:sid)=>pg.exec(`set request.jwt.claim.sub='${user}';set request.jwt.claim.session_id='${session}';`);
  const unlock=async(p=password)=>(await pg.query<{ok:boolean}>('select public.unlock_payments($1) as ok',[p])).rows[0].ok;
  const access=async()=>(await pg.query<{ok:boolean}>('select public.payment_access() as ok')).rows[0].ok;
  const configure=async(enabled=true)=>{await login(admin);await pg.query('select public.unlock_staff($1)',[staffPassword]);await pg.query('select public.set_payment_access($1,$2,$3)',[staff,password,enabled]);await login();};
  const insert=`insert into payments(id,"memberId","membershipId",amount,date,method,status) values('new-payment','member','membership',170,'2026-01-01','Cash','Paid')`;

  await login(admin);
  const staffAccess=async()=>(await pg.query<{ok:boolean}>('select public.staff_access() as ok')).rows[0].ok;
  const unlockStaff=async(p=staffPassword)=>(await pg.query<{ok:boolean}>('select public.unlock_staff($1) as ok',[p])).rows[0].ok;
  assert.equal(await staffAccess(),false);
  assert.equal((await pg.query('select * from staff')).rows.length,1,'locked directory exposes only the caller');
  assert.equal((await pg.query('update staff set name=$1 where id=$2 returning id',['Unauthorized',staff])).rows.length,0,'locked direct API edits cannot change staff');
  await assert.rejects(pg.query('select public.set_payment_access($1,$2,true)',[staff,password]),/Unlock Staff/);
  assert.equal(await unlockStaff(accountPassword),false,'account login password cannot unlock Staff');
  for(let i=0;i<4;i++)assert.equal(await unlockStaff('wrong'),false);
  assert.equal(await unlockStaff(),false,'Staff has a separate five-attempt lockout');
  await pg.exec(`reset role;update private.staff_unlock_attempts set locked_until=now()-interval '1 second';set role authenticated;`);
  assert.equal(await unlockStaff(),true);
  assert.equal(await staffAccess(),true);
  assert.equal((await pg.query('select * from staff')).rows.length,2);
  await assert.rejects(pg.query('update staff set role=$1 where id=$2',['ADMIN',admin]),/own role/);
  await assert.rejects(pg.query('delete from staff where id=$1',[admin]),/own staff access/);
  await pg.query('update staff set role=$1 where id=$2',['ADMIN',staff]);
  await pg.query('update staff set role=$1 where id=$2',['STAFF',staff]);
  await pg.exec(`reset role;update private.staff_sessions set expires_at=now()-interval '1 second';set role authenticated;`);
  assert.equal(await staffAccess(),false,'Staff access expires independently');
  assert.equal(await unlockStaff(),true);
  await pg.exec(`reset role;update auth.users set encrypted_password=extensions.crypt('changed-password',extensions.gen_salt('bf',4)) where id='${admin}';set role authenticated;`);
  assert.equal(await staffAccess(),false,'changing the login password revokes Staff access');
  await pg.exec(`reset role;update auth.users set encrypted_password=extensions.crypt('${accountPassword}',extensions.gen_salt('bf',4)) where id='${admin}';set role authenticated;`);
  assert.equal(await unlockStaff(),true);
  await pg.exec('select public.lock_staff()');
  assert.equal(await staffAccess(),false);

  await login();
  assert.equal(await unlockStaff(),false,'ordinary staff cannot administer permissions');
  assert.equal(await access(),false);
  await assert.rejects(pg.query('select public.import_payments($1::jsonb)',['[]']),/Unlock Payments/);
  assert.equal(await unlock(),false);
  assert.equal((await pg.query('select * from payments')).rows.length,0);
  await pg.exec(insert);
  await pg.query('select public.apply_changes($1::jsonb)',[JSON.stringify([{table:'payments',id:'collection',isNew:true,data:{id:'collection',memberId:'member',membershipId:'membership',amount:100,date:'2026-01-01',method:'Cash',status:'Paid',reference:'',notes:''}}])]);
  await pg.query(`select public.submit_registration('dd',$1::jsonb)`,[JSON.stringify({name:'QR Member',phone:'+60 12 987 6543',email:'qr@example.com',ic:'QR001',dob:'1995-01-01',gender:'Other',address:'',emergencyName:'',emergencyPhone:'',notes:'',consent:true,company:''})]);
  const request=await pg.query<{id:string}>(`select id from public.registration_requests where email='qr@example.com'`);
  await pg.query('select public.approve_registration_memberships($1,$2::jsonb,$3,$4)',[request.rows[0].id,JSON.stringify([{planId:'hybrid-boxing',start:'2026-01-01',months:1,amount:170}]),'Cash','Paid']);
  assert.equal(await access(),false,'QR approval and collections do not unlock the ledger');
  assert.equal((await pg.query('select * from payments')).rows.length,0);
  await pg.exec(`update payments set status='Paid' where id='payment'`);
  await pg.exec(`reset role`);
  assert.equal((await pg.query<{status:string}>(`select status from payments where id='payment'`)).rows[0].status,'Pending');
  await pg.exec(`set role authenticated`);
  await assert.rejects(pg.query('select public.set_payment_access($1,$2,true)',[staff,password]),/Super admin/);
  await assert.rejects(pg.exec('select * from private.payment_credentials'),/permission denied/);
  await configure();
  await login(admin);
  await assert.rejects(pg.query('select public.set_payment_access($1,$2,true)',[staff,'short6']),/at least 7 characters/);
  assert.equal(await access(),false,'super admins also need a separate password');
  await login();
  for(let i=0;i<5;i++)assert.equal(await unlock('wrong'),false);
  assert.equal(await unlock(),false,'lockout also blocks correct passwords');
  await pg.exec(`reset role;update private.payment_credentials set locked_until=now()-interval '1 second';set role authenticated;`);
  assert.equal(await unlock(),true);
  assert.equal(await access(),true);
  assert.equal(await staffAccess(),false,'payment access does not grant staff administration');
  assert.equal((await pg.query('select * from payments')).rows.length,4);
  const importRow={id:'imported',memberId:'member',membershipId:'membership',amount:11,date:'2026-01-01',method:'Cash',status:'Paid',reference:'IMPORT-1',notes:''};
  const importRows=(rows:unknown[])=>pg.query<{count:number}>('select public.import_payments($1::jsonb) as count',[JSON.stringify(rows)]);
  assert.equal((await importRows([importRow])).rows[0].count,1);
  await assert.rejects(importRows([importRow]),/Duplicate payment/);
  await assert.rejects(importRows([{...importRow,id:'rolled-back',reference:'IMPORT-2'},{...importRow,id:'invalid',reference:'IMPORT-3',membershipId:'missing'}]),/membership|foreign key/i);
  assert.equal((await pg.query('select * from payments')).rows.length,5,'invalid batch must not save earlier valid rows');
  await assert.rejects(importRows([{...importRow,id:'precision',reference:'IMPORT-4',amount:1.001}]),/Invalid payment amount/);
  await pg.exec(`update payments set status='Paid' where id='payment'`);
  await login(staff,otherSid);
  assert.equal(await access(),false,'another session cannot inherit the unlock');
  await login();
  await pg.exec(`select public.lock_payments()`);
  assert.equal(await access(),false);
  await assert.rejects(importRows([{...importRow,id:'locked',reference:'IMPORT-5'}]),/Unlock Payments/);
  assert.equal(await unlock(),true);
  await pg.exec(`reset role;update private.payment_sessions set expires_at=now()-interval '1 second';set role authenticated;`);
  assert.equal(await access(),false);
  assert.equal(await unlock(),true);
  await configure(false);
  assert.equal(await access(),false);
  assert.equal(await unlock(),false);
  await configure();
  assert.equal(await unlock(),true);
  await configure();
  assert.equal(await access(),false,'password resets revoke previous unlocks');
  assert.equal(await unlock(),true);
  await pg.exec(`reset role;delete from auth.sessions where id='${sid}';set role authenticated;`);
  assert.equal(await access(),false,'revoked Auth sessions cannot read payments');
  assert.equal(await unlock(),false);
  await pg.exec('set role anon');
  await assert.rejects(pg.exec('select public.staff_access()'),/permission denied/);
  await assert.rejects(pg.exec(insert.replace('new-payment','anonymous-payment')),/permission denied|row-level security/i);
  await assert.rejects(pg.exec('select public.payment_access()'),/permission denied/);
 } finally { await pg.close(); }
});
